/*
 * Reads bundled binary resources (e.g. the example tumor/stroma pixel
 * classifier) from the extension JAR.
 *
 * Kept separate from WorkshopExtension so Groovy scripts can fetch resources
 * reflectively via Class.forName — the same pattern used for WorkshopPrefs — and
 * so the resource is read through THIS class's classloader (the extension
 * classloader), which can actually see the bundled files.
 */
package io.github.sbalci.qupath.workshop;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardCopyOption;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.Arrays;
import java.util.Properties;
import java.util.prefs.Preferences;
import java.util.zip.GZIPInputStream;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

public final class WorkshopResources {

    private static final Logger logger = LoggerFactory.getLogger(WorkshopResources.class);

    private WorkshopResources() {}

    /** Gzipped example classifier bundled in the JAR (decompresses to ~50 MB JSON). */
    private static final String TUMOR_STROMA_CLASSIFIER_GZ = "/classifiers/tumor-stroma-RF.json.gz";

    /**
     * Returns the bundled tumor/stroma pixel-classifier JSON (gunzipped), or
     * {@code null} if the resource is missing or unreadable. Decompresses on each
     * call — callers invoke it at most once per run, so we avoid pinning ~50 MB
     * in memory for the life of the JVM.
     */
    public static String getTumorStromaClassifierJson() {
        try (InputStream raw = WorkshopResources.class.getResourceAsStream(TUMOR_STROMA_CLASSIFIER_GZ)) {
            if (raw == null) {
                return null;
            }
            try (GZIPInputStream gz = new GZIPInputStream(raw)) {
                ByteArrayOutputStream out = new ByteArrayOutputStream(1 << 20);
                byte[] buffer = new byte[1 << 16];
                int read;
                while ((read = gz.read(buffer)) != -1) {
                    out.write(buffer, 0, read);
                }
                return out.toString(StandardCharsets.UTF_8);
            }
        } catch (IOException ex) {
            logger.warn("Failed to read bundled classifier resource: {}", TUMOR_STROMA_CLASSIFIER_GZ, ex);
            return null;
        }
    }

    /** Resource root for bundled Groovy scripts (keep in sync with WorkshopExtension.SCRIPT_RESOURCE_ROOT, which is private). */
    private static final String SCRIPT_RESOURCE_ROOT = "/scripts/";

    /** Resource root for bundled Python bridge runners and requirements.txt files. */
    private static final String PYTHON_RESOURCE_ROOT = "/python/";

    /** Build metadata resource generated by Gradle. */
    private static final String BUILD_INFO_RESOURCE = "/build-info.properties";

    /**
     * Returns the UTF-8 text of a bundled Groovy script (e.g. "sihirbaz.groovy"),
     * or {@code null} if the resource is missing or unreadable. Used by orchestrator
     * scripts (the Modül 6 wizard / selection hub) to launch sibling scripts via GroovyShell.
     */
    public static String getBundledScript(String filename) {
        if (filename == null || filename.isEmpty()) return null;
        String path = SCRIPT_RESOURCE_ROOT + filename;
        try (InputStream raw = WorkshopResources.class.getResourceAsStream(path)) {
            if (raw == null) {
                return null;
            }
            return new String(readAllBytes(raw), StandardCharsets.UTF_8);
        } catch (IOException ex) {
            logger.warn("Failed to read bundled script resource: {}", path, ex);
            return null;
        }
    }

    /**
     * Returns the extension build version from {@code /build-info.properties},
     * falling back to {@code "0.2.2-rc8"} when running from unpacked test classes.
     */
    public static String getExtensionVersion() {
        try (InputStream in = WorkshopResources.class.getResourceAsStream(BUILD_INFO_RESOURCE)) {
            if (in != null) {
                Properties props = new Properties();
                props.load(in);
                String ver = props.getProperty("build.version");
                if (ver != null && !ver.isBlank() && !ver.startsWith("@")) {
                    return ver.trim();
                }
            }
        } catch (IOException ex) {
            logger.debug("Could not read build-info.properties", ex);
        }
        return "0.2.2-rc8";
    }

    /**
     * Returns the UTF-8 text of a bundled Python bridge file (e.g.
     * {@code "classpose/classpose_runner.py"} or {@code "python/classpose/classpose_runner.py"}),
     * or {@code null} if the resource is absent.
     */
    public static String getBundledPythonBridgeText(String relativePath) {
        String norm = normalizePythonRelativePath(relativePath);
        if (norm == null) return null;
        String resPath = PYTHON_RESOURCE_ROOT + norm;
        try (InputStream raw = WorkshopResources.class.getResourceAsStream(resPath)) {
            if (raw == null) return null;
            return new String(readAllBytes(raw), StandardCharsets.UTF_8);
        } catch (IOException ex) {
            logger.warn("Failed to read bundled Python bridge resource: {}", resPath, ex);
            return null;
        }
    }

    /**
     * Extracts a bundled Python bridge resource from classpath {@code /python/<relativePath>}
     * to {@code <atolyeDataRoot>/bridges/<version>/<relativePath>} (defaulting to
     * {@code ~/.atolye/bridges/<version>/<relativePath>}) when missing or when size/SHA-256
     * differs, and returns its {@link Path} (or {@code null} if the resource does not exist).
     */
    public static Path extractBundledPythonBridge(String relativePath) {
        Path root = resolveAtolyeDataRoot()
                .resolve("bridges")
                .resolve(sanitizePathSegment(getExtensionVersion()));
        return extractBundledPythonBridge(relativePath, root);
    }

    /**
     * Extracts a bundled Python bridge resource from classpath {@code /python/<relativePath>}
     * into {@code targetRoot.resolve(normalizedRelativePath)} when missing or when size/SHA-256
     * differs, returning the extracted {@link Path} or {@code null} if not bundled.
     */
    public static Path extractBundledPythonBridge(String relativePath, Path targetRoot) {
        if (targetRoot == null) return null;
        String norm = normalizePythonRelativePath(relativePath);
        if (norm == null) return null;
        Path extracted = extractSinglePythonResource(norm, targetRoot);
        if (extracted != null && norm.endsWith(".py")) {
            int slash = norm.lastIndexOf('/');
            if (slash > 0) {
                String reqRel = norm.substring(0, slash + 1) + "requirements.txt";
                extractSinglePythonResource(reqRel, targetRoot);
            }
        }
        return extracted;
    }

    private static Path extractSinglePythonResource(String normalizedRel, Path targetRoot) {
        String resPath = PYTHON_RESOURCE_ROOT + normalizedRel;
        byte[] expectedBytes;
        try (InputStream raw = WorkshopResources.class.getResourceAsStream(resPath)) {
            if (raw == null) {
                return null;
            }
            expectedBytes = readAllBytes(raw);
        } catch (IOException ex) {
            logger.warn("Failed to read bundled Python resource: {}", resPath, ex);
            return null;
        }

        Path dest = targetRoot;
        for (String seg : normalizedRel.split("/")) {
            dest = dest.resolve(seg);
        }

        try {
            if (Files.isRegularFile(dest) && Files.size(dest) == expectedBytes.length) {
                byte[] existingBytes = Files.readAllBytes(dest);
                if (Arrays.equals(sha256(existingBytes), sha256(expectedBytes))) {
                    return dest.toAbsolutePath();
                }
            }
            Path parent = dest.getParent();
            if (parent != null) {
                Files.createDirectories(parent);
            }
            Path tmp = Files.createTempFile(parent != null ? parent : targetRoot, ".bridge-", ".tmp");
            try {
                Files.write(tmp, expectedBytes);
                try {
                    Files.move(tmp, dest, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
                } catch (IOException atomicEx) {
                    Files.move(tmp, dest, StandardCopyOption.REPLACE_EXISTING);
                }
            } finally {
                Files.deleteIfExists(tmp);
            }
            return dest.toAbsolutePath();
        } catch (IOException ex) {
            logger.warn("Failed to extract bundled Python bridge {} to {}", resPath, dest, ex);
            return null;
        }
    }

    static String normalizePythonRelativePath(String relativePath) {
        if (relativePath == null) return null;
        String norm = relativePath.trim().replace('\\', '/');
        while (norm.startsWith("/")) {
            norm = norm.substring(1);
        }
        if (norm.startsWith("python/")) {
            norm = norm.substring("python/".length());
        }
        if (norm.isEmpty() || norm.contains(":") || norm.endsWith("/")) {
            return null;
        }
        String[] parts = norm.split("/");
        for (String part : parts) {
            if (part.isEmpty() || ".".equals(part) || "..".equals(part)) {
                return null;
            }
        }
        return norm;
    }

    private static Path resolveAtolyeDataRoot() {
        try {
            String configured = Preferences.userRoot().node("/qupath/atolye/common").get("dataRoot", "");
            if (configured != null && !configured.isBlank()) {
                return Paths.get(configured.trim());
            }
        } catch (Throwable ignored) {
            // Fall back to ~/.atolye if Preferences backend is unavailable
        }
        return Paths.get(System.getProperty("user.home", "."), ".atolye");
    }

    private static String sanitizePathSegment(String raw) {
        if (raw == null || raw.isBlank()) return "default";
        return raw.trim().replaceAll("[^A-Za-z0-9._-]", "_");
    }

    private static byte[] readAllBytes(InputStream in) throws IOException {
        ByteArrayOutputStream out = new ByteArrayOutputStream(1 << 15);
        byte[] buffer = new byte[1 << 14];
        int read;
        while ((read = in.read(buffer)) != -1) {
            out.write(buffer, 0, read);
        }
        return out.toByteArray();
    }

    private static byte[] sha256(byte[] data) {
        try {
            return MessageDigest.getInstance("SHA-256").digest(data);
        } catch (NoSuchAlgorithmException ex) {
            throw new IllegalStateException("SHA-256 unavailable", ex);
        }
    }
}
